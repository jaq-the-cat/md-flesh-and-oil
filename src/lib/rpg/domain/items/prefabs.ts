/** Omit collapses a union, so it has to be applied to each member separately. */
type WithoutId<T> = T extends unknown ? Omit<T, "id"> : never;

/** The key is the id, so it is written once and every reference is checked. */
const catalogue = <T extends Record<string, WithoutId<ItemTemplate>>>(entries: T) =>
  Object.fromEntries(Object.entries(entries).map(([id, item]) => [id, { ...item, id }])) as unknown as {
    [K in keyof T]: T[K] & { id: K };
  };

