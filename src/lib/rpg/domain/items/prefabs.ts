/** The definition behind a carried item, whether it came from the catalogue or the player. */
export function templateOf(item: Item): ItemTemplate | CustomTemplate | undefined {
  return isCustom(item.template) ? item.template : ITEMS[item.template as ItemId];
}

function round(value: number) {
  return parseFloat(value.toFixed(2));
}

/** A liquid's contents count toward its weight; every other kind is a fixed figure. */
export function itemWeight(item: Item) {
  const template = templateOf(item);
  if (!template) return 0;
  const contents = template.kind === "liquid" ? (item.current ?? 0) * template.weightPerUnit : 0;
  return round(template.weight + contents);
}

export function containerWeight(items: Item[]) {
  return round(items.reduce((total, item) => total + itemWeight(item), 0));
}
