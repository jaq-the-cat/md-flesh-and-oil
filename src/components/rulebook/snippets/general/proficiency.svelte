<h2>Proficiency and Expertise</h2>
<p>
  With Proficiency, you get a +12 bonus to the relevant roll. With Expertise, the
  bonus is +25.
</p>
<p>
  You should create a character with 2 Proficiencies and 1 Expertise. Some species
  (such as Worker Drones) can pick a second Expertise during character creation, and
  have a cap of 3 instead of 2.
</p>
<p>
  You can level up your skills by rolling above a natural 90 (90 on the die, not
  counting modifiers).
</p>
