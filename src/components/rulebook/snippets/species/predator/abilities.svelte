<h2>Abilities</h2>
<h3>Eat
</h3>
<p>
  Can be used on a dead body (Human or Drone) to drain their entire Fresh Oil
  reserve at once. Eating someone during combat takes 2 turns to complete.
</p>
<h2>Drone Repair</h2>
<p>
  When there are no healing items available, Predator Drones can be repaired using
  parts, a tool such as screwdriver or wrench, and a bonding agent.
</p>
<p>Predator Drones can be repaired with Worker or Disassembly Drone parts.</p>
<p>The difficulty is the missing HP of the player to be healed.</p>
<p>
  The healing amount is generally dependant on the specific parts used, but
  there are some static:
</p>
<ul>
  <li>Intact Drone Parts heal for 1d40 + Mechanics HP.</li>
  <li>Damaged Drone Parts heal for 1d20 + Mechanics HP.</li>
  <li>Replacing a damaged limb heals for 1/4 + Mechanics Max HP.</li>
</ul>
