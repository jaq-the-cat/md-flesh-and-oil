<h2>Sanity</h2>
<p>
  Your maximum Sanity is your Willpower bonus, so a character with low Willpower has very
  little to lose.
</p>
<p>
  Sanity is increased after a Long Rest by 50. If it reaches 0, they go Insane, allowing them
  to use Bite and Eat on other people. Eating a Human or Drone without being Insane triggers a
  Willpower check, with the difficulty being your missing Sanity. If you fail, become Insane.
</p>
<h2>Traumatic Events</h2>
<p>
  Decreases Sanity by 10. Can happen in a variety of ways, including watching another player
  die or another Human or Drone get eaten.
</p>
