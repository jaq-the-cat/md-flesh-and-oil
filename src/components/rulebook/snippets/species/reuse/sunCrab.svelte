<h2>Sunlight</h2>
<p>
  Solver Drones take Max HP / 10 Hunger damage when out in the Sun or when
  exposed to other sources of UV Radiation.
</p>
<h2>Core Crab</h2>
<p>
  Solver Drones can have their cores removed by a Pierce attack aimed at
  the chest that deals more than 25% of their Max HP in damage, which turns them
  into a Core Crab. They have 10 HP and +0 in every check except Finesse, in
  which they have a +30. While in Core form, they can attempt to get back inside
  their bodies if they're within melee range by running a Finesse check
  against their body's Vigor bonus. If the original body dies, the Core is
  forcefully removed and cannot get back into the body until it is repaired.
</p>
