<h2>Absolute Solver</h2>
<p>
  Solver-enabled Drones have a special bar called Absolute Solver, and a matching skill of the
  same name keyed to Dexterity and Intelligence. Absolute Solver rolls use that skill bonus
  like any other check.
</p>
<p>
  If the bar reaches 100, the Drone has to roll a Willpower check at difficulty 50 + Missing
  HP. If failed, they fall under the influence of the Solver. While under its influence, they
  become an enemy. They can come back to normal if another person succeeds in a Persuasion
  check. If they have an emotional connection (partner, family member, etc) to the Drone under
  the influence of the Solver, gain Advantage.
</p>
<p>
  Absolute Solver goes up by 10 for every 100 Oil (1 whole Drone/Human) you consume.
</p>
<p>Having Absolute Solver above 80 turns the Drone's visor color to Yellow.</p>
