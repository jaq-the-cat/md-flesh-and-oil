<h2>Oil</h2>
<p>
  Drones run on an Oil reserve of 100. They spend 20 Oil during a Short Rest and 50 Oil
  during a Long Rest.
</p>
<h3>Non-Solver Drones</h3>
<p>
  They replenish their Oil by drinking from an Oil reserve or by eating Batteries, at a rate
  of 10 Oil per Battery.
</p>
<h3>Solver-enabled Drones</h3>
<p>
  They replenish their Oil by using Bite (with or without consent) on a Drone or a Human at a
  rate of 1 Blood to 2 Oil, or by using Eat on a dead body. They may also spend 10 Oil to
  bring their Absolute Solver down by 20.
</p>
<h3>Losing Oil</h3>
<p>
  Whenever they take more than 20 damage, they roll a 1d20 and lose 2 times that amount in
  Oil, up to a maximum of 50 oil lost per hit.
</p>
<p>At 0 Oil, take Max HP / 10 damage per turn until death or replenishment.</p>
