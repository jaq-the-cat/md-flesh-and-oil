<h2>Dronification [NC]</h2>
<p>
  A Human that gets a bit too intimate with JCJenson™ Nanites may be turned
  into a Drone. The type of Drone is decided by the infecting Drone's type or,
  if caused by an exterior factor, by rolling a 1d40, with 1-20 being a Worker
  Drone, 21-30 being a Solver Drone, and 31-40 being a Disassembly Drone.
</p>
